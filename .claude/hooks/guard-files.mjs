#!/usr/bin/env node
// PreToolUse(Edit|Write): files that must not be edited by hand.
import path from 'node:path';
import { readInput, relPath, denyPreToolUse } from './_lib.mjs';

const input = await readInput();
const rel = relPath(input);
if (!rel) process.exit(0);
const name = path.basename(rel);

if (/^(package-lock\.json|pnpm-lock\.yaml|yarn\.lock|bun\.lockb?)$/.test(name)) {
  denyPreToolUse(`${name} is generated. Change package.json and run the package manager instead of editing the lockfile.`);
}
if (name === 'CHANGELOG.md' || name === '.release-please-manifest.json') {
  denyPreToolUse(`${name} is generated by release-please. Use Conventional Commits; never edit it by hand.`);
}
if (/\.(jks|keystore|p12|pem)$/i.test(name) || /^\.env(\..+)?$/.test(name)) {
  denyPreToolUse(`${name} may hold secrets or signing keys and must not be created or edited by the agent.`);
}
